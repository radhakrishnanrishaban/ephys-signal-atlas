"""
Render results/SCOREBOARD.md from results/scoreboard.csv, with lab health at the top (D-14).

    python -m bench.scoreboard    # re-render only; scores come from python -m bench.run

Lab health uses public data only, as of the render date: release tags (`v*`) and the
front matter of lab notes in results/notes/ (`date: YYYY-MM-DD`, `experiments: [EXP-001]`).
"""

from __future__ import annotations

import csv
import re
import subprocess
from datetime import date, timedelta
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

from bench.spec import SPEC, DecoderSpec
from bench.splits import SPLITS_PATH

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "results"
NOTES = RESULTS / "notes"
SCOREBOARD_CSV = RESULTS / "scoreboard.csv"
SCOREBOARD_MD = RESULTS / "SCOREBOARD.md"
GAP_BINS = {"kept_1_7d": (1, 7), "kept_8_30d": (8, 30), "kept_31d_plus": (31, 10**6)}
SCOREBOARD_COLUMNS = [
    "run_date", "commit", "spec", "splits", "feature", "causal", "seeds", "sessions", "pairs",
    "cfd_days", "cfd_ci95_lo", "cfd_ci95_hi", "cfd_seed_min", "cfd_seed_max",
    "same_day_r2_median", *GAP_BINS, "month_plus_r2_median",
    "decoder_macs_per_bin", "feature_state_bytes_per_ch", "fits", "runtime_s",
]
HEALTH_WEEKS = 4


def release_tags() -> List[Tuple[str, date]]:
    out = subprocess.run(
        ["git", "for-each-ref", "refs/tags/v*", "--format=%(refname:short) %(creatordate:short)"],
        cwd=REPO, capture_output=True, text=True, check=True,
    ).stdout.split()
    return [(name, date.fromisoformat(day)) for name, day in zip(out[::2], out[1::2])]


def lab_notes() -> List[Tuple[date, Set[str]]]:
    """(date, experiment IDs) from each note's front matter."""
    notes = []
    for path in sorted(NOTES.glob("*.md")):
        head = path.read_text().split("---")[1] if path.read_text().startswith("---") else ""
        day = re.search(r"^date:\s*(\d{4}-\d{2}-\d{2})", head, re.M)
        if day:
            notes.append((date.fromisoformat(day.group(1)), set(re.findall(r"EXP-\d{3}", head))))
    return notes


def _week(d: date) -> Tuple[int, int]:
    return tuple(d.isocalendar()[:2])


def lab_health(today: date, tags: List[Tuple[str, date]], notes: List[Tuple[date, Set[str]]]) -> Dict:
    shipped = {_week(d) for _, d in tags if d <= today} | {_week(d) for d, _ in notes if d <= today}
    streak, week_start = 0, today
    while _week(week_start) in shipped:
        streak += 1
        week_start -= timedelta(weeks=1)
    past_tags = sorted((d, name) for name, d in tags if d <= today)
    window_start = today - timedelta(days=today.weekday()) - timedelta(weeks=HEALTH_WEEKS - 1)
    experiments = set().union(*[ids for d, ids in notes if window_start <= d <= today])
    return {
        "ship_streak_weeks": streak,
        "last_release": past_tags[-1] if past_tags else None,
        "experiments_last_4_weeks": sorted(experiments),
    }


def health_lines(today: date) -> List[str]:
    h = lab_health(today, release_tags(), lab_notes())
    last = h["last_release"]
    since = f"{(today - last[0]).days} ({last[1]}, {last[0]})" if last else "no release yet"
    exps = h["experiments_last_4_weeks"]
    return [
        f"## Lab health (as of {today})",
        "",
        "| Ship streak | Days since last release | Experiments, last 4 weeks |",
        "| --- | --- | --- |",
        f"| {h['ship_streak_weeks']} week(s) | {since} | {len(exps)} ({', '.join(exps) or 'none'}) |",
        "",
        "Ship streak counts ISO weeks with a release tag or a lab note in `results/notes/`. "
        "The release being prepared is not counted in days since last release (D-14).",
        "",
    ]


def render(spec: DecoderSpec = SPEC, today: Optional[date] = None) -> None:
    with SCOREBOARD_CSV.open() as fh:
        rows = list(csv.DictReader(fh))
    lines = [
        "# Scoreboard",
        "",
        "Generated by `python -m bench.run` (or `python -m bench.scoreboard`) from `results/scoreboard.csv`; "
        "do not edit by hand. Every published number cites a row here by commit and feature (D-08).",
        "",
        *health_lines(today or date.today()),
        "## Scores",
        "",
        f"Spec `{spec.spec_id}`: Ridge on SBP(t…t−{spec.window_bins}) → velocity(t+{spec.lag_bins}), "
        f"first {spec.warmup_bins} bins of each session unscored, same-day R² from "
        f"{spec.same_day_folds} blocked folds, cross-day pairs from `bench/{SPLITS_PATH.name}`. "
        f"CFD = longest gap where the isotonic fit of kept ratio ≥ {spec.kept_threshold:.0%} (`bench/cfd.py`), "
        f"median over seeds {', '.join(map(str, spec.seeds))} (each shifts the same-day fold grid); "
        f"95 % CI from {spec.n_boot:,} session-resampled draws per seed, pooled. "
        "CFD is written only for causal features; acausal rows are reference R² values (D-13). "
        "Cost: decoder multiply-accumulates per 20 ms bin and float64 feature state per channel; "
        "rows before these columns existed have them empty.",
        "",
        "`commit` is the private development commit that produced the row. Each public release tag lists "
        "the development commits it contains (`git show <tag>`), and a release is refused unless `bench/` and "
        "`02_package/src/` match the newest row's commit (D-14).",
        "",
        "| " + " | ".join(SCOREBOARD_COLUMNS) + " |",
        "| " + " | ".join("---" for _ in SCOREBOARD_COLUMNS) + " |",
        *("| " + " | ".join(r.get(c) or "" for c in SCOREBOARD_COLUMNS) + " |" for r in rows),
        "",
    ]
    SCOREBOARD_MD.write_text("\n".join(lines))


if __name__ == "__main__":
    render()
    print(f"wrote {SCOREBOARD_MD.relative_to(REPO)}")
